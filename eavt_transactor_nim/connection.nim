proc scanDatomsSafe(eng: SharedEngine; cf: int): seq[eavt.Datom] {.
    raises: [ValueError].} =
  try:
    var res: seq[eavt.Datom]
    for d in eng.store.eavt.scanDatoms(cf):
      res.add(d)
    res
  except Exception as e:
    raise (ref ValueError)(msg: e.msg)


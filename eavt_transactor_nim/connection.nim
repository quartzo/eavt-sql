proc writeFrameAsync(transp: StreamTransport; body: string) {.async.} =
  var buf = newSeq[byte](4 + body.len)
  buf[0] = byte(body.len shr 24); buf[1] = byte(body.len shr 16)
  buf[2] = byte(body.len shr 8); buf[3] = byte(body.len)
  if body.len > 0:
    copyMem(addr buf[4], addr body[0], body.len)
  discard await transp.write(buf)

proc writeFrameQueued(eng: SharedEngine; transp: StreamTransport;
                      body: string) {.async.} =
  ## Despacho de saída por transporte: conexão com subscrição de replicação
  ## → fila única do subscriber (ordem wal-antes-de-response estrutural);
  ## conexão direta (sem replicate) → escrita direta, como antes.
  let sub = eng.hub.find(transp)
  if sub != nil and not sub.closed:
    sub.enqueueResponse(body)
  else:
    await transp.writeFrameAsync(body)

proc writeResponseAsync(eng: SharedEngine; transp: StreamTransport;
                        columns: seq[string];
                        rows: seq[seq[SExpr]]; more: bool;
                        error: string = ""; id: string = "") {.async.} =
  var ms = MsgStream.init(256)
  var fieldCount = 1  # "more"
  if id.len > 0: inc fieldCount
  if error.len > 0:
    inc fieldCount  # "error"
  else:
    fieldCount += 2  # "columns" + "rows"
  ms.pack_map(fieldCount)
  if id.len > 0:
    ms.pack("id"); ms.pack(id)
  if error.len > 0:
    ms.pack("error"); ms.pack(error)
    ms.pack("more"); ms.pack(false)
  else:
    ms.pack("columns")
    ms.pack_array(columns.len)
    for c in columns: ms.pack(c)
    ms.pack("rows")
    ms.pack_array(rows.len)
    for row in rows:
      ms.pack_array(row.len)
      for v in row:
        writeSExprPlain(ms, v)
    ms.pack("more"); ms.pack(more)
  await eng.writeFrameQueued(transp, ms.data)

proc writeErrorAsync(eng: SharedEngine; transp: StreamTransport; msg: string;
                     id: string = "") {.async.} =
  await writeResponseAsync(eng, transp, @[], @[], false, msg, id)

proc nextBatchSafe(sess: StreamingSession; maxRows: int): (seq[seq[SExpr]], bool) {.
    raises: [ValueError].} =
  try:
    sess.nextBatch(maxRows)
  except Exception as e:
    raise (ref ValueError)(msg: e.msg)

